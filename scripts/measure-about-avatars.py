"""Measure original avatar alpha bounds; write layout metadata only, never edit images."""
from pathlib import Path
import hashlib, json
from PIL import Image
app = Path(__file__).resolve().parents[1]
ids = ['mai','bao-lan','yen-nhi','hoang-lan','quynh-nhu','khoi-nguyen']
frames, manifest = {}, []
for ident in ids:
    frames[ident] = {}
    for kind in ['portrait','avatar']:
        path = app / f'public/about-us/{kind}-{ident}.webp'
        image = Image.open(path).convert('RGBA')
        bounds = image.getchannel('A').getbbox()
        if bounds is None: raise ValueError(f'Empty artwork: {path.name}')
        frames[ident][kind] = {'canvas': list(image.size), 'bounds': list(bounds)}
        manifest.append({'file': f'public/about-us/{path.name}', 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), **frames[ident][kind]})
(app / 'src/content/about-us-art.ts').write_text('// Generated by scripts/measure-about-avatars.py from original alpha bounds.\nexport const aboutArtworkFrames = ' + json.dumps(frames, indent=2) + ' as const;\n')
(app / 'assets/about-us/avatar-measurements.json').write_text(json.dumps(manifest, indent=2)+'\n')
print('Measured 12 original images; no artwork modified.')
